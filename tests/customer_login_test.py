# Returning customers on the booking page: "I've booked before" → code → filled in; booking links from texts.
# Needs the local engine + gateway + site (see README) with a customer +64211000001 (two addresses, notes)
# and a link in link.txt from customer_link_make. Usage: python3 tests/customer_login_test.py <link-file>
import re
from playwright.sync_api import sync_playwright, expect
BASE = 'http://localhost:3360'
BOOK = f'{BASE}/book?a=plumbing.leak.basin.flowing'
link = open(__import__('sys').argv[1]).read().strip()
with sync_playwright() as p:
    b = p.chromium.launch(); c = b.new_context(viewport={'width': 1200, 'height': 1000}); pg = c.new_page()
    errs = []; pg.on('console', lambda m: m.type == 'error' and errs.append(m.text))
    pg.goto(BOOK)
    pg.screenshot(path='login_0.png')
    pg.get_by_role('button', name="I've booked before").click()
    pg.get_by_label('Mobile number').fill('021 100 0001')
    pg.get_by_role('button', name='Text me a code').click()
    expect(pg.get_by_text('Test mode:')).to_be_visible()
    code = re.search(r'code: (\d{6})', pg.locator('p', has_text='Test mode:').inner_text()).group(1)
    pg.screenshot(path='login_1.png')
    # wrong code first
    pg.get_by_label('6-digit code').fill('000000' if code != '000000' else '111111')
    pg.get_by_role('button', name='Sign in').click()
    expect(pg.locator('p[role=alert]')).to_contain_text("isn't right")
    pg.get_by_label('6-digit code').fill(code)
    pg.get_by_role('button', name='Sign in').click()
    expect(pg.get_by_text('Welcome back, Ana.')).to_be_visible()
    print('1. signed in with code')
    pg.get_by_label("What's happening?").fill('Basin tap is leaking under the vanity')
    pg.get_by_role('button', name='Continue').click()
    expect(pg.get_by_text('Your addresses')).to_be_visible()
    print('2. addresses:', pg.locator('fieldset').first.inner_text().replace('\n', ' / '))
    print('   notes:', pg.get_by_text('We already have these notes').locator('..').inner_text().replace('\n', ' / '))
    pg.screenshot(path='login_2.png', full_page=True)
    # choose the other address, then "somewhere else", then back
    pg.get_by_text('7 Surrey Cres, Grey Lynn').click()
    expect(pg.get_by_text('We already have these notes')).to_have_count(0)
    pg.get_by_text('Somewhere else').click()
    expect(pg.get_by_label('Street address')).to_have_value('')
    pg.get_by_text('12 Ponsonby Rd, Ponsonby').click()
    pg.get_by_label('Anything new for the plumber? (optional)').fill('New gate code 8899')
    pg.get_by_role('button', name='Continue').click()
    pg.get_by_text('Mon', exact=True).click()
    pg.get_by_role('button', name='Continue').click()
    expect(pg.get_by_label('Your name')).to_have_value('Ana Smith')
    expect(pg.get_by_label('Mobile')).to_have_value('0211000001')
    expect(pg.get_by_label('Email')).to_have_value('ana@test.nz')
    print('3. details filled in')
    pg.get_by_role('button', name='Continue').click()
    print('4. review:', pg.locator('dl').first.inner_text().replace('\n', ' / ')[:200])
    # stays signed in on reload; sign out
    pg.goto(BOOK); expect(pg.get_by_text('Welcome back, Ana.')).to_be_visible()
    pg.get_by_role('button', name='Not you? Sign out').click()
    expect(pg.get_by_role('button', name="I've booked before")).to_be_visible()
    pg.goto(BOOK); expect(pg.get_by_role('button', name="I've booked before")).to_be_visible()
    print('5. reload keeps you signed in; sign out works')
    # unknown number: same message, no code
    pg.get_by_role('button', name="I've booked before").click()
    pg.get_by_label('Mobile number').fill('021 999 9999')
    pg.get_by_role('button', name='Text me a code').click()
    expect(pg.get_by_text("If you've booked with us using that number")).to_be_visible()
    expect(pg.get_by_text('Test mode:')).to_have_count(0)
    print('6. unknown number: same message, nothing revealed')
    # link from a text, in a fresh browser
    c2 = b.new_context(viewport={'width': 390, 'height': 850}); p2 = c2.new_page()
    p2.goto(link); p2.screenshot(path='login_link.png')
    p2.goto(link)   # opening twice (like a link preview) doesn't use it up
    p2.get_by_role('button', name='Continue').click()
    p2.wait_for_url('**/get-started?welcome=1')
    expect(p2.get_by_text('Welcome back, Ana.')).to_be_visible()
    p2.screenshot(path='login_link_2.png')
    p2.goto(BOOK); expect(p2.get_by_text('Welcome back, Ana.')).to_be_visible()
    p2.screenshot(path='login_phone_book.png')
    print('7. text link signs in')
    p3 = b.new_context().new_page(); p3.goto(link); p3.get_by_role('button', name='Continue').click()
    expect(p3.get_by_text('That link has expired')).to_be_visible()
    print('8. used link refused; errors:', errs)
    b.close()
